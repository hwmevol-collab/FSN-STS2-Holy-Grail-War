def walk(b,start,end,depth=0):
    assert depth<20
    p=start;out=[]
    while p<end:
        if not any(b[p:end]):break
        typ,head,size=struct.unpack_from('<HHI',b,p)
        assert size>=8 and (head==0 if typ&0x8000 else size>=head>=8) and p+size<=end,(p,typ,head,size,end)
        if typ==4:
            assert head>=16
            name=b[p+16:p+head].split(b'\0',1)[0].decode('utf-8')
            out.append(dict(source_chunk_offset=p,source_chunk_type=typ,source_name=name))
        if typ in {2,3}:out+=walk(b,p+head,p+size,depth+1)
        p+=size
    return out
